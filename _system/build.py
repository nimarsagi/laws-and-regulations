"""Build the law library from the three texts in _sources/.

    python3 _system/build.py

Splits each source into one file per article, annex, recital or guidelines
section, adds frontmatter and a links footer, writes the CONTEXT.md lists and
_index/definitions.md, and picks up from review-map/ which review areas point
at each file. It then re-reads every file it wrote and checks that each
non-blank line of each source sits in exactly one file, word for word, and
that every link in the library resolves. Exits 1 if any check fails.

ai-act/, gdpr/, guidelines-art5/ and _index/ are wiped and rebuilt on every
run, so never edit them by hand: change a source or this script and rerun.
"""
