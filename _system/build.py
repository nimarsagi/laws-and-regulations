def read_back(rel):
    text = (ROOT / rel).read_text(encoding="utf-8")
    end = text.index("\n---\n", 4)
    fm, rest = text[4:end], text[end + 5:]
    rest = rest.split(LINKS_MARK)[0]
    body, _, fns = rest.partition(FOOTNOTES_MARK)
    keep = lambda part: [l for l in part.split("\n") if l.strip() and l != STAMP]
    return fm, keep(body), keep(fns)


def verify(units, structures, src):
    problems = []
    for law, lines in src.items():
        mine = [u for u in units if u.law == law]
        seen = defaultdict(int)
        for u in mine:
            for i in u.pulled + u.body + u.fns:
                seen[i] += 1
            fm, body, fns = read_back(u.rel)
            want = [lines[i] for i in u.pulled + u.body if lines[i].strip()]
            if body != want:
                problems.append(f"{u.rel}: text differs from the source")
            if fns != [lines[i] for i in u.fns]:
                problems.append(f"{u.rel}: footnotes differ from the source")
        for i in structures[law]:
            seen[i] += 1
            if not is_structure(lines[i]):
                problems.append(f"{law} line {i + 1} was left out but is not a heading, separator or blank")
        # every chapter and section heading that was left out must survive in the next file's frontmatter
        for i in structures[law]:
            if m := (CHAPTER.match(lines[i]) or SECTION.match(lines[i])):
                nxt = min((u for u in mine if u.body and min(u.body) > i), key=lambda u: min(u.body))
                if sentence_case(m.group(2)) not in read_back(nxt.rel)[0]:
                    problems.append(f"{law} line {i + 1}: heading not kept in {nxt.rel}")
        missing = [i + 1 for i in range(len(lines)) if seen[i] == 0]
        twice = [i + 1 for i, n in seen.items() if n > 1]
        if missing:
            problems.append(f"{law}: lines not placed anywhere: {missing[:10]}")
        if twice:
            problems.append(f"{law}: lines placed twice: {twice[:10]}")
    return problems


def check_links():
    broken, count = [], 0
    for p in ROOT.rglob("*.md"):
        rel = p.relative_to(ROOT).as_posix()
        if rel.startswith(("_sources/", ".git/")):
            continue
        for target in re.findall(r"\]\(([^)\s]+)\)", p.read_text(encoding="utf-8")):
            if re.match(r"[a-z]+:", target) or target.startswith("#"):
                continue
            count += 1
            if not (p.parent / target.split("#")[0]).exists():
                broken.append(f"{rel} → {target}")
    return count, broken


