# The sources mix ordinary and non-breaking spaces (the 2026 amendment's headings use the latter), so "\s".
MARKER = re.compile(r"^▼([A-Z]+\d*)$")
DELETED = re.compile(r"^▼([A-Z]+\d*)\s—+$")
SEPARATOR = re.compile(r"^-{3,}$")
CHAPTER = re.compile(r"^## CHAPTER\s([IVX]+)\s—\s(.+)$")
SECTION = re.compile(r"^### (?:SECTION|Section)\s(\d+)\s—\s(.+)$")
ARTICLE = re.compile(r"^#### Article\s(\d+[a-z]?)(?:\s—\s(.+))?$")
