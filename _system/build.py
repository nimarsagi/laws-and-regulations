def wipe_generated():
    for d in GENERATED_DIRS:
        p = ROOT / d
        if not p.exists():
            continue
        for f in p.rglob("*"):
            if f.is_file() and f.name != ".DS_Store":
                if f.suffix != ".md" or STAMP not in f.read_text(encoding="utf-8"):
                    sys.exit(f"stop: {f.relative_to(ROOT)} was not written by build.py; move it out of {d}/ first")
        shutil.rmtree(p)


def main():
    src = {law: (ROOT / path).read_text(encoding="utf-8").split("\n") for law, path in SOURCES.items()}
    wipe_generated()
    aia, aia_s = parse_ai_act(src["ai-act"])
    gdpr, gdpr_s = parse_gdpr(src["gdpr"])
    guides, gl_s = parse_guidelines(src["guidelines"])
    units = aia + gdpr + guides
    structures = {"ai-act": aia_s, "gdpr": gdpr_s, "guidelines": gl_s}
    by_key = {u.key: u for u in units}
    known = defaultdict(list)
    for u in units:
        known[(u.law, u.kind)].append(u.num)

    out_refs, in_refs, unresolved = {}, defaultdict(set), defaultdict(int)
    for u in units:
        text = body_text(u, src[u.law]) + "\n" + "\n".join(src[u.law][i] for i in u.fns)
        keys, missing = find_refs(text, u.law, by_key, known)
        keys = sorted(set(keys) - {u.key}, key=sort_key)
        out_refs[u.key] = keys
        for x in keys:
            in_refs[x].add(u.key)
        for m in missing:
            unresolved[re.sub(r" \d.*| [IVX]+.*", "", m)] += 1
        u.meta["tokens"] = tokens(body_text(u, src[u.law]) + "\n".join(src[u.law][i] for i in u.fns))

    areas = review_areas(units)
    for u in units:
        write_unit(u, src[u.law], unit_fields(u, src[u.law], areas),
                   footer(u, out_refs, in_refs, areas, by_key, guides))

    aia_version = src["ai-act"][0].split(" — ")[2]
    law_contexts(units, "ai-act", "AI Act — articles and annexes",
                 f"Regulation (EU) 2024/1689, consolidated text of {aia_version}, one file per article or annex, "
                 "word for word. It includes amendment M1, Regulation (EU) 2026/1744 of 8 July 2026. In the text, "
                 "`▼B` starts original 2024 wording, `▼M1` starts wording M1 added or replaced, and `▼M1 —————` marks "
                 "wording M1 deleted. Files marked 2026 below differ from the 2024 text: read them rather than rely "
                 "on memory.\n\nPath of any article: `ai-act/<chapter folder>/art-NNN.md`, three digits "
                 "(Art 4a is `art-004a.md`). Annexes: `ai-act/annexes/annex-NN.md`. Sizes are in tokens. Each "
                 "file ends with links to what it cites, what cites it, and the review areas that use it. "
                 "Defined terms: `_index/definitions.md`. The AI Act's recitals are not in this library.",
                 src["ai-act"])
    law_contexts(units, "gdpr", "GDPR — articles and recitals",
                 "Regulation (EU) 2016/679 as published in the Official Journal on 4 May 2016, one file per "
                 "article or recital, word for word. Later corrections are not included.\n\nPath of any article: "
                 "`gdpr/<chapter folder>/art-NNN.md`, three digits. Sizes are in tokens. Each file ends with "
                 "links to what it cites, what cites it, and the review areas that use it. Defined terms: "
                 "`_index/definitions.md`.", src["gdpr"])
    guideline_contexts(units)
    n_defs = definitions(units, src)

    problems = verify(units, structures, src)
    n_links, broken = check_links()
    problems += [f"broken link: {b}" for b in broken]

    count = lambda law, kind: sum(1 for u in units if u.law == law and u.kind == kind)
    print(f"AI Act: {count('ai-act', 'article')} articles, {count('ai-act', 'annex')} annexes; "
          f"{sum(1 for u in aia if u.meta.get('changed_2026'))} changed in 2026")
    print(f"GDPR: {count('gdpr', 'article')} articles, {count('gdpr', 'recital')} recitals")
    print(f"Guidelines: {len(guides)} files, {sum(len(u.fns) for u in guides)} footnotes placed")
    print(f"Definitions indexed: {n_defs}")
    print(f"References linked: {sum(len(v) for v in out_refs.values())}; not in this library: "
          + ", ".join(f"{n} × {what}" for what, n in sorted(unresolved.items(), key=lambda x: -x[1])))
    print(f"Review areas found on {len(areas)} files")
    biggest = sorted(units, key=lambda u: -u.meta["tokens"])[:5]
    print("Biggest files: " + ", ".join(f"{u.cite} {k(u.meta['tokens'])}" for u in biggest))
    if problems:
        print(f"\nFAILED — {len(problems)} problem(s):")
        for p in problems[:40]:
            print("  " + p)
        sys.exit(1)
    lines_total = sum(sum(1 for l in lines if l.strip()) for lines in src.values())
    left_out = sum(1 for law, s in structures.items() for i in s if src[law][i].strip())
    print(f"\nCheck passed: all {lines_total} non-blank source lines are accounted for — "
          f"{lines_total - left_out} sit word for word in exactly one file, {left_out} are chapter/section "
          f"headings (kept in frontmatter) or separator lines. {n_links} links resolve.")


if __name__ == "__main__":
    main()
