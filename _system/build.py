RECITAL = re.compile(r"^\*\*\((\d+)\)\*\*")
PARA = re.compile(r"^\*\*\((\d+)\)\*\*")
GL_HEAD = re.compile(r"^(#{2,6}) (?:(\d+(?:\.\d+)*)\.?\s+)?(.+)$")
FN_REF = re.compile(r"\[\^(\d+)\](?!:)")
FN_DEF = re.compile(r"^\[\^(\d+)\]:")
ADOPTED = "HAVE ADOPTED THIS REGULATION:"

# Cross-references. A bare "Article N" means the same law (the AI Act, inside the guidelines);
# "of Regulation (EU) 2016/679" / "GDPR" and "of Regulation (EU) 2024/1689" / "AI Act" switch law;
# any other act ("of Directive …", "of the Charter", "TFEU", "of that Regulation") is skipped.
NUM = r"\d+[a-z]?"
SUB = r"(?:\((?:\d+[a-z]?|[a-z]{1,3}|[ivx]+)\))*"
ART_RE = re.compile(rf"\bArticles?\s+({NUM})(?![\d/]){SUB}((?:\s*(?:,|and/or|and|or|to)\s*{NUM}(?![\d/]){SUB})*)")
ART_ITEM = re.compile(rf"(,|and/or|and|or|to)\s*({NUM})(?![\d/])")
ANNEX_RE = re.compile(r"\bAnnex(?:es)?\s+([IVX]+)\b((?:\s*(?:,|and|or|to)\s*[IVX]+\b)*)")
ANNEX_ITEM = re.compile(r"(,|and|or|to)\s*([IVX]+)\b")
RECITAL_RE = re.compile(r"\b[Rr]ecitals?\s+(\d+)\b((?:\s*(?:,|and|or|to)\s*\d+\b)*)")
RECITAL_ITEM = re.compile(r"(,|and|or|to)\s*(\d+)\b")
QUAL = re.compile(
    r"(?:[\s,]+|(?:and/or|and|or|to)\b|\([^()\s]{1,6}\)"
    r"|(?:first|second|third|fourth|fifth|sixth|last)\s+(?:subparagraph|sentence)|points?\b|paragraphs?\b)*"
)


@dataclass
class Unit:
    law: str      # ai-act | gdpr | guidelines
    kind: str     # article | annex | recital | section | front | footnotes
    num: str
    title: str
    rel: str      # path from the library root
    body: list    # source line numbers (0-based), in file order
    pulled: list = field(default_factory=list)  # ▼ markers moved from just before a heading into this unit
    fns: list = field(default_factory=list)     # guidelines: footnote lines, moved from the end of the source
    chapter: str = ""
    section: str = ""
    meta: dict = field(default_factory=dict)

    @property
    def key(self):
        return (self.law, self.kind, self.num)

    @property
    def cite(self):
        law = {"ai-act": "AI Act", "gdpr": "GDPR", "guidelines": "Art 5 Guidelines"}[self.law]
        return {
            "article": f"{law} Art {self.num}", "annex": f"{law} Annex {self.num}",
            "recital": f"{law} Recital {self.num}", "section": f"{law} §{self.num}",
            "front": f"{law}, title page", "footnotes": f"{law}, footnotes",
        }[self.kind]

    def label(self, from_law):
        if self.law == from_law and self.law != "guidelines":
            return self.cite.split(" ", 2 if self.law == "ai-act" else 1)[-1]
        return self.cite.replace("Art 5 Guidelines ", "Guidelines ")


def tokens(text):
    return max(1, round(len(text) / 4))


def k(n):
    return f"{n / 1000:.1f}k"


def roman(s):
    vals = {"I": 1, "V": 5, "X": 10, "L": 50, "C": 100}
    return sum(-vals[c] if i + 1 < len(s) and vals[s[i + 1]] > vals[c] else vals[c] for i, c in enumerate(s))


def sentence_case(s):
    if not s.isupper():
        return s
    s = s.lower()
    s = s[0].upper() + s[1:]
    return re.sub(r"\b(ai|eu)\b", lambda m: m.group(1).upper(), s)


def art_file(num):
    m = re.match(r"(\d+)([a-z]?)$", num)
    return f"art-{int(m.group(1)):03d}{m.group(2)}.md"


def is_structure(line):
    return (not line.strip() or SEPARATOR.match(line) or CHAPTER.match(line)
            or SECTION.match(line) or line == ADOPTED)


def carve(lines, starts, end):
    """Cut lines[starts[0]:end] into units, one per start. Blank lines, separators, chapter and
    section headings just before the next start are left out as structure; a bare ▼ marker among
    them moves into the next unit, because it describes the text that follows it."""
    cuts, structure, pending = [], [], []
    for n, s in enumerate(starts):
        e = starts[n + 1] if n + 1 < len(starts) else end
        j = e
        while j > s + 1 and (is_structure(lines[j - 1]) or MARKER.match(lines[j - 1])):
            j -= 1
        cuts.append((pending, list(range(s, j))))
        pending = []
        for g in range(j, e):
            (pending if MARKER.match(lines[g]) else structure).append(g)
    if pending:
        sys.exit(f"stop: ▼ marker at line {pending[0] + 1} has no text after it")
    return cuts, structure


def headings_at(lines, idx):
    """Chapter and section in force at each line."""
    chapter, section, out = ("", ""), ("", ""), {}
    for i, line in enumerate(lines):
        if m := CHAPTER.match(line):
            chapter, section = (m.group(1), sentence_case(m.group(2))), ("", "")
        elif m := SECTION.match(line):
            section = (m.group(1), m.group(2))
        if i in idx:
            out[i] = (chapter, section)
    return out


def article_title(lines, i, m):
    if m.group(2):
        return m.group(2).strip().rstrip("'’ ")
    for line in lines[i + 1:i + 6]:
        if line.startswith("##### "):
            return line[6:].strip()
    return ""


def annex_title(lines, i, m):
    if m.group(2):
        return m.group(2).strip()
    for line in lines[i + 1:i + 6]:
        if line.strip() and not MARKER.match(line):
            return line.lstrip("# ").strip()
    return ""


def law_units(lines, law, heads, front_title, fn_start, chapter_names):
    """Units for a law: title page, one per head (article, annex or recital), footnotes."""
    head_lines = [h[0] for h in heads]
    cuts, structure = carve(lines, [0] + head_lines + [fn_start], len(lines))
    where = headings_at(lines, set(head_lines))
    units = [Unit(law, "front", "", front_title, f"{law}/_front.md", cuts[0][1], cuts[0][0])]
    seen_chapters = set()
    for (i, kind, num, title), (pulled, body) in zip(heads, cuts[1:-1]):
        (ch_num, ch_title), (sec_num, sec_title) = where[i]
        u = Unit(law, kind, num, title, "", body, pulled)
        if kind == "article":
            n = roman(ch_num)
            seen_chapters.add(n)
            if n not in chapter_names:
                sys.exit(f"stop: {law} chapter {ch_num} has no folder name in build.py")
            u.rel = f"{law}/ch-{n:02d}_{chapter_names[n]}/{art_file(num)}"
            u.chapter = f"{ch_num} — {ch_title}"
            u.section = f"{sec_num} — {sec_title}" if sec_num else ""
        elif kind == "annex":
            u.rel = f"{law}/annexes/annex-{roman(num):02d}.md"
        else:
            u.rel = f"{law}/recitals/rec-{int(num):03d}.md"
        units.append(u)
    if seen_chapters != set(chapter_names):
        sys.exit(f"stop: {law} chapters found {sorted(seen_chapters)} don't match the folder names in build.py")
    pulled, body = cuts[-1]
    units.append(Unit(law, "footnotes", "", "Footnotes (Official Journal references)", f"{law}/_footnotes.md", body, pulled))
    return units, structure


def parse_ai_act(lines):
    heads = []
    for i, line in enumerate(lines):
        if m := ARTICLE.match(line):
            heads.append((i, "article", m.group(1), article_title(lines, i, m)))
        elif m := ANNEX.match(line):
            heads.append((i, "annex", m.group(1), annex_title(lines, i, m)))
    last = heads[-1][0]
    fn_start = next(i for i in range(last, len(lines)) if re.match(r"^\( \\?\*?\d+ \)", lines[i]))
    units, structure = law_units(lines, "ai-act", heads, "Title and amendment list", fn_start, AIA_CHAPTERS)
    # Which text the 2026 amendment (M1) touched: a ▼ marker holds until the next one.
    state, current = [], None
    for line in lines:
        if m := MARKER.match(line):
            current = m.group(1)
        state.append(current)
    for u in units:
        if u.kind not in ("article", "annex"):
            continue
        text = [i for i in u.body if lines[i].strip() and not MARKER.match(lines[i]) and not lines[i].startswith("#")]
        changed = [state[i] not in (None, "B") for i in text]
        if text and all(changed):
            u.meta["changed_2026"] = "all"
        elif any(changed) or any(DELETED.match(lines[i]) for i in u.body):
            u.meta["changed_2026"] = "part"
    return units, structure


def parse_gdpr(lines):
    adopted = lines.index(ADOPTED)
    heads = [(i, "recital", RECITAL.match(lines[i]).group(1), "")
             for i in range(adopted) if RECITAL.match(lines[i])]
    for i in range(adopted, len(lines)):
        if m := ARTICLE.match(lines[i]):
            heads.append((i, "article", m.group(1), article_title(lines, i, m)))
    fn_start = next(i for i in range(heads[-1][0], len(lines)) if lines[i].startswith("(1) "))
    return law_units(lines, "gdpr", heads, "Title, legal bases and opening", fn_start, GDPR_CHAPTERS)


def parse_guidelines(lines):
    fn_start = next(i for i, line in enumerate(lines) if FN_DEF.match(line))
    fn_line = {FN_DEF.match(lines[i]).group(1): i for i in range(fn_start, len(lines)) if FN_DEF.match(lines[i])}
    nodes = []
    for i in range(fn_start):
        if m := GL_HEAD.match(lines[i]):
            nodes.append({"i": i, "lv": len(m.group(1)), "num": m.group(2), "title": m.group(3).strip()})
    for n, nd in enumerate(nodes):
        nd["end"] = next((x["i"] for x in nodes[n + 1:] if x["lv"] <= nd["lv"]), fn_start)

    def kids(nd, lv):
        return [x for x in nodes if x["lv"] == lv and nd["i"] < x["i"] < nd["end"]]

    def size(a, b):
        text = "\n".join(lines[a:b])
        return tokens(text + "".join(lines[fn_line[f]] for f in set(FN_REF.findall(text))))

    plan = []  # (start line, heading node, top-level section number)
    for top in (x for x in nodes if x["lv"] == 2):
        t = int(top["num"])
        k3 = kids(top, 3)
        if not k3:
            plan.append((top["i"], top, t))
        for a, s3 in enumerate(k3):
            start3 = top["i"] if a == 0 else s3["i"]
            k4 = kids(s3, 4)
            if size(start3, s3["end"]) > GUIDE_SPLIT_AT and k4:
                for b, s4 in enumerate(k4):
                    plan.append((start3 if b == 0 else s4["i"], s4, t))
            else:
                plan.append((start3, s3, t))
    plan[0] = (0, plan[0][1], plan[0][2])  # the document title goes with section 1
    cuts, structure = carve(lines, [p[0] for p in plan], fn_start)
    units, used = [], {}
    for (start, nd, t), (pulled, body) in zip(plan, cuts):
        name = GL_NAMES[t]
        if nd["lv"] == 2:
            rel = f"guidelines-art5/{name}.md"
        else:
            rel = f"guidelines-art5/{name}/{nd['num'].replace('.', '-')}.md"
        u = Unit("guidelines", "section", nd["num"], nd["title"], rel, body, pulled)
        u.meta["top"] = t
        u.meta["includes"] = [x["num"] for x in nodes if start <= x["i"] < nd["i"] and x["num"]]
        text = "\n".join(lines[i] for i in body)
        for f in dict.fromkeys(FN_REF.findall(text)):
            if f in used:
                sys.exit(f"stop: guidelines footnote {f} is referenced from two files")
            used[f] = rel
            u.fns.append(fn_line[f])
        paras = [int(m.group(1)) for i in body if (m := PARA.match(lines[i]))]
        if paras:
            u.meta["paras"] = f"{paras[0]}–{paras[-1]}" if len(paras) > 1 else str(paras[0])
        units.append(u)
    missing = set(fn_line) - set(used)
    if missing:
        sys.exit(f"stop: guidelines footnotes never referenced: {sorted(missing, key=int)}")
    structure += [i for i in range(fn_start, len(lines)) if not lines[i].strip()]
    return units, structure


# ---------- cross-references ----------

def act_of(tail, default):
    head = tail[QUAL.match(tail).end():][:100]
    if re.match(r"(?:of\s+(?:the\s+)?)?(?:GDPR\b|General Data Protection Regulation|Regulation\s*\(EU\)\s*2016/679)", head):
        return "gdpr"
    if re.match(r"(?:of\s+(?:the\s+)?)?(?:AI Act\b|Artificial Intelligence Act|Regulation\s*\(EU\)\s*2024/1689)", head):
        return "ai-act"
    if re.match(r"of\s+this\s+Regulation", head):
        return default
    if re.match(r"of\s+\S|thereof\b|to\s+(?:the\s+)?(?:Regulation|Directive|Decision|Treaty)|[A-Z]{2,}\b", head):
        return None
    return default


def ref_items(first, rest, item_re, to_int):
    items = [(first, first)]
    for sep, num in item_re.findall(rest):
        if sep == "to":
            items[-1] = (items[-1][0], num)
        else:
            items.append((num, num))
    return [(to_int(a), to_int(b), a, b) for a, b in items]


def base(num):
    m = re.match(r"(\d+)([a-z]?)", num)
    return int(m.group(1)), m.group(2)


def find_refs(text, own, keys_in_library, known):
    """Return (resolved keys, unresolved descriptions) for the references in text.
    known maps (law, kind) to the numbers that exist, for expanding "Articles 8 to 15"."""
    default = "ai-act" if own == "guidelines" else own
    keys, missing = [], []
    patterns = [
        (ART_RE, ART_ITEM, "article", lambda s: base(s)[0]),
        (ANNEX_RE, ANNEX_ITEM, "annex", roman),
        (RECITAL_RE, RECITAL_ITEM, "recital", int),
    ]
    for pat, item_re, kind, to_int in patterns:
        for m in pat.finditer(text):
            act = act_of(text[m.end():m.end() + 160], default)
            if act is None:
                continue
            for lo, hi, a, b in ref_items(m.group(1), m.group(2), item_re, to_int):
                if a == b:
                    targets = [a] if (act, kind, a) in keys_in_library else []
                elif kind == "article":  # "Articles 74 to 84" includes the inserted 75a-75d
                    targets = [n for n in known.get((act, kind), [])
                               if lo <= base(n)[0] <= hi and not (base(n)[0] == hi and base(n)[1])]
                else:
                    targets = [n for n in known.get((act, kind), []) if lo <= to_int(n) <= hi]
                if targets:
                    keys += [(act, kind, n) for n in targets]
                else:
                    missing.append(f"{act} {kind} {a}" + ("" if a == b else f"-{b}"))
    return keys, missing


# ---------- review areas ----------

LINK = re.compile(r"\]\(([^)\s]+?\.md)(?:#[^)]*)?\)")


def review_areas(units):
    by_rel = {u.rel: u for u in units}
    areas = defaultdict(set)
    folder = ROOT / "review-map"
    if not folder.is_dir():
        return areas
    for f in sorted(folder.glob("*.md")):
        if f.name == "CONTEXT.md":
            continue
        for target in LINK.findall(f.read_text(encoding="utf-8")):
            if target.startswith("http"):
                continue
            rel = os.path.relpath((f.parent / target).resolve(), ROOT).replace(os.sep, "/")
            if rel in by_rel:
                areas[rel].add(f.stem)
            elif rel.endswith("/CONTEXT.md"):  # a link to a folder list covers every file in it
                d = rel[: -len("CONTEXT.md")]
                for r in by_rel:
                    if r.startswith(d):
                        areas[r].add(f.stem)
    return areas


# ---------- writing ----------

def yq(v):
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def frontmatter(fields):
    out = ["---"]
    for key, v in fields.items():
        if v in (None, "", []):
            continue
        if isinstance(v, list):
            out.append(f"{key}: [" + ", ".join(yq(x) for x in v) + "]")
        elif isinstance(v, int):
            out.append(f"{key}: {v}")
        else:
            out.append(f"{key}: {yq(v)}")
    out.append("---")
    return "\n".join(out)


def link(from_rel, to_rel):
    return os.path.relpath(ROOT / to_rel, (ROOT / from_rel).parent).replace(os.sep, "/")


def body_text(u, lines):
    out = [lines[i] for i in u.pulled] + ([""] if u.pulled else []) + [lines[i] for i in u.body]
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out)


def unit_fields(u, lines, areas):
    first, last = min(u.body) + 1, max(u.body) + 1
    # aliases: lets Obsidian find a file by its citation ("GDPR Art 6"), since file names repeat across laws
    f = {"cite": u.cite, "aliases": [u.cite], "title": u.title, "chapter": u.chapter, "section": u.section}
    if u.law == "guidelines":
        f["covers"] = GL_COVERS.get(u.meta["top"], "")
        f["paras"] = u.meta.get("paras", "")
        f["includes"] = [f"heading and opening text of §{n}" for n in u.meta["includes"]]
    f["changed_2026"] = u.meta.get("changed_2026", "")
    f["tokens"] = u.meta["tokens"]
    f["source"] = f"{SOURCES[u.law]} lines {first}-{last}" + (" + footnotes" if u.fns else "")
    f["areas"] = sorted(areas.get(u.rel, []))
    return f


def footer(u, out_refs, in_refs, areas, by_key, guide_units):
    rows = []

    def links(keys, label_law):
        return " · ".join(f"[{by_key[x].label(label_law)}]({link(u.rel, by_key[x].rel)})" for x in keys)

    refs = out_refs[u.key]
    if refs:
        rows.append(f"**Refers to:** {links(refs, u.law)}")
    incoming = sorted((x for x in in_refs[u.key] if x[0] != "guidelines"), key=sort_key)
    if incoming:
        rows.append(f"**Referred to by:** {links(incoming, u.law)}")
    if u.key == ("ai-act", "article", "5"):
        parts = []
        for t, covers in GL_COVERS.items():
            target = next(g for g in guide_units if g.meta["top"] == t)
            path = target.rel if target.rel.count("/") == 1 else target.rel.rsplit("/", 1)[0] + "/CONTEXT.md"
            parts.append(f"{covers}: [§{t}]({link(u.rel, path)})")
        rows.append("**Commission guidelines on this article** (July 2025, before the 2026 amendment, "
                    "so nothing on points (ba), (bb), (1a) or (1b)): " + " · ".join(parts))
    else:
        from_guides = sorted((x for x in in_refs[u.key] if x[0] == "guidelines"), key=sort_key)
        if from_guides:
            rows.append(f"**Discussed in the Art 5 guidelines:** {links(from_guides, u.law)}")
    if areas.get(u.rel):
        rows.append("**Review areas:** " + " · ".join(
            f"[{a}]({link(u.rel, f'review-map/{a}.md')})" for a in sorted(areas[u.rel])))
    return "\n\n".join(rows) if rows else "_No links._"


def sort_key(key):
    law, kind, num = key
    order = {"ai-act": 0, "gdpr": 1, "guidelines": 2}[law], {"front": 0, "article": 1, "annex": 2, "recital": 3, "section": 4, "footnotes": 5}[kind]
    if kind == "article":
        return (*order, *base(num))
    if kind == "annex":
        return (*order, roman(num), "")
    if kind == "section":
        return (*order, tuple(int(x) for x in num.split(".")), "")
    return (*order, int(num) if num else 0, "")


def write(rel, text):
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8")


def write_unit(u, lines, fields, foot):
    parts = [frontmatter(fields), STAMP, "", body_text(u, lines)]
    if u.fns:
        parts += ["", FOOTNOTES_MARK, "", "\n".join(lines[i] for i in u.fns)]
    parts += ["", LINKS_MARK, "", foot]
    write(u.rel, "\n".join(parts))


def flag(u):
    return {"all": " · new or rewritten 2026", "part": " · changed 2026"}.get(u.meta.get("changed_2026"), "")


def law_contexts(units, law, name, intro, lines):
    arts = [u for u in units if u.law == law and u.kind == "article"]
    top = [f"# {name}", "", STAMP, "", intro, ""]
    chapters = {}
    for u in arts:
        chapters.setdefault(u.rel.split("/")[1], []).append(u)
    for folder, members in chapters.items():
        ch = members[0].chapter
        top += [f"## Chapter {ch} · `{folder}/`", ""]
        sub = [f"# {name.split(' — ')[0]} — Chapter {ch}", "", STAMP, "",
               f"Articles {members[0].num}–{members[-1].num}. Up: [the full list](../CONTEXT.md).", ""]
        section = ""
        for u in members:
            if u.section != section:
                top += ([""] if top[-1] else []) + [f"### Section {u.section}", ""]
                sub += ([""] if sub[-1] else []) + [f"## Section {u.section}", ""]
            section = u.section
            top.append(f"- {u.num} {u.title} · {k(u.meta['tokens'])}{flag(u)}")
            sub.append(f"- [Art {u.num}]({art_file(u.num)}) {u.title} · {k(u.meta['tokens'])}{flag(u)}")
        top.append("")
        write(f"{law}/{folder}/CONTEXT.md", "\n".join(sub))
    annexes = [u for u in units if u.law == law and u.kind == "annex"]
    if annexes:
        top += ["## Annexes · `annexes/`", ""]
        sub = [f"# {name.split(' — ')[0]} — Annexes", "", STAMP, "", "Up: [the full list](../CONTEXT.md).", ""]
        for u in annexes:
            top.append(f"- {u.num} {u.title} · {k(u.meta['tokens'])}{flag(u)}")
            sub.append(f"- [Annex {u.num}]({u.rel.rsplit('/', 1)[1]}) {u.title} · {k(u.meta['tokens'])}{flag(u)}")
        write(f"{law}/annexes/CONTEXT.md", "\n".join(sub))
        top.append("")
    recitals = [u for u in units if u.law == law and u.kind == "recital"]
    if recitals:
        top += ["## Recitals · `recitals/`", "",
                f"Recitals 1–{recitals[-1].num}, one file each: `recitals/rec-NNN.md`. "
                "They explain the articles but don't bind on their own. "
                "The list with each recital's opening words is in [recitals/CONTEXT.md](recitals/CONTEXT.md).", ""]
        sub = [f"# {name.split(' — ')[0]} — Recitals", "", STAMP, "",
               "Opening words of each recital. Up: [the full list](../CONTEXT.md).", ""]
        for u in recitals:
            text = re.sub(r"^\*\*\(\d+\)\*\*\s*", "", lines[u.body[0]])
            words = text.split()
            sub.append(f"- [{u.num}]({u.rel.rsplit('/', 1)[1]}) {' '.join(words[:14])}{' …' if len(words) > 14 else ''}")
        write(f"{law}/recitals/CONTEXT.md", "\n".join(sub))
    top += ["Also here: `_front.md` (title page) and `_footnotes.md` (Official Journal references)."]
    write(f"{law}/CONTEXT.md", "\n".join(top))


def guideline_contexts(units):
    guides = [u for u in units if u.law == "guidelines"]
    top = ["# Commission guidelines on AI Act Article 5 (prohibited practices)", "", STAMP, "",
           "C(2025) 5052 final, 29 July 2025. Not binding: this is the Commission's reading of Article 5, "
           "and only the EU Court of Justice can interpret the AI Act with authority (paragraph 5). "
           "Written before the 2026 amendment, so it says nothing on Article 5(1)(ba), (bb), (1a) or (1b).", "",
           "One file per subsection; subsections over ~6k tokens are split one heading level down, and a "
           "section's opening text goes with its first file. Each file carries its own footnotes. "
           "Paragraph numbers run through the whole document: cite as \"Art 5 Guidelines para N\".", ""]

    def line(u, base_rel):
        extra = f" (starts with the opening of §{', §'.join(u.meta['includes'])})" if u.meta["includes"] else ""
        paras = f" · paras {u.meta['paras']}" if u.meta.get("paras") else ""
        return f"- [{u.num} {u.title}]({link(base_rel, u.rel)}){extra}{paras} · {k(u.meta['tokens'])}"

    for t, name in GL_NAMES.items():
        members = [u for u in guides if u.meta["top"] == t]
        covers = f" — {GL_COVERS[t]}" if t in GL_COVERS else ""
        if members[0].rel.count("/") == 1:
            top.append(line(members[0], "guidelines-art5/CONTEXT.md") + covers)
            continue
        top += ["", f"## {t} · `{name}/`{covers}", ""]
        sub = [f"# Art 5 Guidelines — section {t}", "", STAMP, "",
               f"Covers: {GL_COVERS.get(t, '')}. Up: [all sections](../CONTEXT.md).", ""]
        for u in members:
            top.append(line(u, "guidelines-art5/CONTEXT.md"))
            sub.append(line(u, f"guidelines-art5/{name}/CONTEXT.md"))
        write(f"guidelines-art5/{name}/CONTEXT.md", "\n".join(sub))
        top.append("")
    write("guidelines-art5/CONTEXT.md", "\n".join(top))


DEF_LINE = re.compile(r"^\*\*\((\d+[a-z]?)\)\*\*\s+(.*)$")


def definitions(units, src):
    entries = []
    for key in [("ai-act", "article", "3"), ("gdpr", "article", "4")]:
        u = next(x for x in units if x.key == key)
        for i in u.body:
            m = DEF_LINE.match(src[u.law][i])
            if not m:
                continue
            before, sep, after = m.group(2).partition(" means")
            if not sep:
                continue
            terms = re.findall(r"‘([^’]+)’", before) + re.findall(r"\(‘([^’]+)’\)", after)
            entries += [(t, f"{u.cite}({m.group(1)})") for t in terms]
    entries.sort(key=lambda e: (e[0].lower(), e[1]))
    aia = next(x for x in units if x.key == ("ai-act", "article", "3")).rel
    gdpr = next(x for x in units if x.key == ("gdpr", "article", "4")).rel
    out = ["# Defined terms", "", STAMP, "",
           f"Every term defined in AI Act Art 3 (`{aia}`) and GDPR Art 4 (`{gdpr}`), A–Z. "
           "Each definition is one line in its article file, so grep for the term to read it without "
           f"loading the whole article: `grep \"‘deployer’\" {aia}`.", ""]
    out += [f"- {t} — {c}" for t, c in entries]
    write("_index/definitions.md", "\n".join(out))
    return len(entries)


